"""Bring outside commits merged on a publication repository back to the monorepo, the source of truth.

Without this the next publication stops with "Publication repository contains manual drift".
Each changed public file maps to its monorepo source through `.publication.json` `copiedFiles`:
- `copy`: the public content is copied over the source while the source still equals the published file;
  if the monorepo changed it since, a 3-way `git merge-file` (base = the published file) merges both edits.
  Whole-file content, not a re-rooted patch: no path rewriting, and a clean merge is exact.
- `vendored-strip-import`, `generated`, new, deleted or conflicting files: listed under "Needs a person".
One PR per public head; nothing is written when its branch or PR exists already.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

from common import OWNER, RELEASE_BRANCH, ROOT, SOURCE_NAME, allowlist, commit, git, load, run, url
from reviewed_publication import BOT, BOT_EMAIL

MAIN = f'origin/{RELEASE_BRANCH}'
TYPE = re.compile(r'([a-z]+)(?:\([^)]*\))?!?: ')
PR_NUMBER = re.compile(r'\(#(\d+)\)\Z')
REASONS = {'vendored-strip-import': 'vendored with imports stripped; undo the transform by hand',
           'generated': 'generated by the exporter; change its template or input instead',
           None: 'not in copiedFiles (a new file); decide where it belongs in the monorepo',
           'deleted': 'deleted on the public repository',
           'conflict': 'conflicts with monorepo changes made since the publication'}


def digest(data):
    return hashlib.sha256(data).hexdigest() if data is not None else None


def blob(repo, rev, path):
    """File bytes at `rev`, None when absent. Bytes, because `run` strips output."""
    if not git(repo, 'ls-tree', '--name-only', rev, '--', path):
        return None
    return subprocess.run(['git', '-C', str(repo), 'cat-file', 'blob', f'{rev}:{path}'],
                          capture_output=True, check=True).stdout


def is_bot(commit_):
    return commit_['name'] == BOT or bool(BOT_EMAIL.fullmatch(commit_['email']))


def log(repo, *args):
    fields = ('sha', 'name', 'email', 'subject')
    out = git(repo, 'log', '--format=%H%x1f%an%x1f%ae%x1f%s', *args)
    return [dict(zip(fields, line.split('\x1f'))) for line in out.splitlines()]


def last_publication(repo):
    """The newest bot commit that changed `.publication.json`; an outside edit to it is not a publication."""
    return next(c['sha'] for c in log(repo, MAIN, '--', '.publication.json') if is_bot(c))


def outside_commits(repo, since):
    return [c for c in log(repo, '--reverse', '--no-merges', f'{since}..{MAIN}') if not is_bot(c)]


def changed_paths(repo, commits):
    return sorted({p for c in commits
                   for p in git(repo, 'diff-tree', '--no-commit-id', '--name-only', '-r', c['sha']).splitlines()})


def merge(mine, base, theirs):
    """3-way merge of one file; None on conflicts."""
    with tempfile.TemporaryDirectory(prefix='sync-back-merge-') as temp:
        files = [Path(temp) / n for n in ('mine', 'base', 'theirs')]
        for path, data in zip(files, (mine, base or b'', theirs)):
            path.write_bytes(data)
        result = subprocess.run(['git', 'merge-file', '-p', *map(str, files)], capture_output=True)
    if result.returncode < 0 or result.returncode > 127:
        raise RuntimeError('git merge-file failed: ' + result.stderr.decode())
    return None if result.returncode else result.stdout


def plan(repo, provenance, since, paths, mono):
    """({source: bytes} to write, [(public path, reason)] for a person, [(public path, source, how)] applied)."""
    mapping = {c['output']: c for c in provenance['copiedFiles']}
    published = provenance['fileHashes']
    writes, people, applied = {}, [], []
    for path in paths:
        current = blob(repo, MAIN, path)
        if digest(current) == published.get(path):
            continue  # changed and changed back
        entry = mapping.get(path) or {}
        transform = entry.get('transform')
        if transform != 'copy' or current is None:
            people.append((path, REASONS['deleted' if current is None and transform == 'copy' else transform]))
            continue
        source = mono / entry['source']
        mine = source.read_bytes() if source.is_file() else None
        if mine == current:
            continue  # already synced back
        if mine is not None and digest(mine) == published[path]:
            writes[entry['source']], how = current, 'copied'
        else:
            merged = merge(mine, blob(repo, since, path), current) if mine is not None else None
            if merged is None:
                people.append((path, REASONS['conflict']))
                continue
            writes[entry['source']], how = merged, 'merged 3-way'
        applied.append((path, entry['source'], how))
    return writes, people, applied


def commit_type(commits, allowed):
    """One commit keeps its own Conventional Commit type, so Release Please versions it as the public PR would.
    Several squash into one: feat if any, else fix if any (the bump the separate commits would give), else chore."""
    types = [m.group(1) for c in commits if (m := TYPE.match(c['subject'])) and m.group(1) in allowed]
    if len(commits) == 1 and types:
        return types[0]
    return next((t for t in ('feat', 'fix') if t in types), 'chore')


def coauthors(commits):
    seen = dict.fromkeys(f'Co-authored-by: {c["name"]} <{c["email"]}>' for c in commits)
    return list(seen)


def texts(key, repository, commits, applied, people, head):
    allowed = {s['type'] for s in load(ROOT / 'release-please-config.json')['changelog-sections']}
    title = f'{commit_type(commits, allowed)}({key}): sync back public changes'
    public = f'https://github.com/{OWNER}/{repository}'
    lines = []
    for c in commits:
        number = PR_NUMBER.search(c['subject'])
        pr = f' ({public}/pull/{number.group(1)})' if number else ''
        lines.append(f'- [`{c["sha"][:7]}`]({public}/commit/{c["sha"]}) {c["subject"]} by {c["name"]}{pr}')
    trailers = '\n'.join(coauthors(commits))
    message = f'{title}\n\n' + '\n'.join(f'- {c["sha"][:7]} {c["subject"]}' for c in commits) + f'\n\n{trailers}\n'
    body = [f'Outside changes merged on [{repository}]({public}) after its last publication, brought back so the '
            'next publication does not stop on manual drift.', '', '## Public commits', *lines, '', '## Applied',
            *([f'- `{p}` -> `{s}` ({how})' for p, s, how in applied] or ['- nothing']), '']
    if people:
        body += ['## Needs a person', *[f'- [`{p}`]({public}/blob/{head}/{p}): {why}' for p, why in people], '']
    body += [trailers]
    return title, message, '\n'.join(body) + '\n'


def clone(key, destination):
    run(['git', 'clone', '--quiet', '--no-checkout', url(key), destination])


def existing(branch):
    """The sync branch or a PR from it (any state) on the monorepo."""
    if run(['git', 'ls-remote', '--heads', 'origin', f'refs/heads/{branch}']):
        return f'branch {branch}'
    prs = run(['gh', 'pr', 'list', '--repo', f'{OWNER}/{SOURCE_NAME}', '--head', branch, '--state', 'all',
               '--json', 'url', '--jq', '.[].url'])
    return prs.splitlines()[0] if prs else None


def publish_pr(work, branch, title, message, body):
    commit(work, message)
    git(work, 'push', 'origin', f'HEAD:refs/heads/{branch}')
    body_file = work.parent / 'sync-back-pr.md'
    body_file.write_text(body)
    return run(['gh', 'pr', 'create', '--repo', f'{OWNER}/{SOURCE_NAME}', '--base', RELEASE_BRANCH,
                '--head', branch, '--title', title, '--body-file', body_file])


def sync_back(key, dry_run=False):
    repository = allowlist()[key]
    with tempfile.TemporaryDirectory(prefix=f'sync-back-{key}-') as temp:
        temp = Path(temp)
        repo = temp / 'public'
        clone(key, repo)
        provenance = json.loads(blob(repo, MAIN, '.publication.json'))
        since = last_publication(repo)
        commits = outside_commits(repo, since)
        if not commits:
            return f'Nothing to sync for {key}: no outside commits after publication {since[:7]}'
        head = commits[-1]['sha']
        branch = f'chore/sync-back-{key}-{head[:7]}'
        found = existing(branch)
        if found:
            return f'Already synced or in review: {found}'
        paths = changed_paths(repo, commits)
        if dry_run:
            writes, people, applied = plan(repo, provenance, since, paths, ROOT)  # the checkout, read only
            title, message, body = texts(key, repository, commits, applied, people, head)
            if not writes and not people:
                return f'[dry run] Nothing to sync for {key}: the checkout already has every public change'
            return f'[dry run] branch {branch}\n\ncommit message:\n{message}\nPR title: {title}\nPR body:\n{body}'
        work = temp / 'monorepo'
        git(ROOT, 'fetch', '--quiet', 'origin', RELEASE_BRANCH)
        git(ROOT, 'worktree', 'add', '--detach', work, MAIN)
        try:
            writes, people, applied = plan(repo, provenance, since, paths, work)
            title, message, body = texts(key, repository, commits, applied, people, head)
            if not writes:
                if people:
                    raise SystemExit('Nothing applies automatically; needs a person:\n' + body)
                return f'Nothing to sync for {key}: the monorepo already has every public change'
            for source, data in writes.items():
                (work / source).write_bytes(data)
            return publish_pr(work, branch, title, message, body)
        finally:
            git(ROOT, 'worktree', 'remove', '--force', work)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('package', choices=list(allowlist()))
    parser.add_argument('--dry-run', action='store_true', help='print the plan; write nothing')
    args = parser.parse_args()
    print(sync_back(args.package, args.dry_run))
